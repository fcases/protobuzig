        input: []const u8,
        format: BinaraFormato,
    ) !Self {
        return .{
            .impl = try TextoInfoImpl.deseriigiElBin(
                allocator,
                input,
                format,
            ),
        };
    }

    pub fn deserializeFromFile(
        allocator: std.mem.Allocator,
